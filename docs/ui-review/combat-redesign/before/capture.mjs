import { chromium } from '/var/lib/bazworker/workspace/stormwreck-combat-companion/node_modules/playwright-core/index.mjs';
import fs from 'node:fs';
const dir='/var/lib/bazworker/workspace/stormwreck-combat-companion/docs/ui-review/combat-redesign/before';
const browser=await chromium.launch({headless:true});
const results={timestamp:new Date().toISOString(),url:'http://127.0.0.1:4173/stormwreck-combat-companion/',checks:[],geometry:{}};
for(const width of [375,390,1440]){
const page=await browser.newPage({viewport:{width,height:width===1440?1000:844}});
await page.goto(results.url); await page.screenshot({path:`${dir}/empty-${width}.png`,fullPage:true});
await page.getByRole('button',{name:'Roster & sheets',exact:true}).click();
await page.screenshot({path:`${dir}/roster-${width}.png`,fullPage:true});
await page.getByRole('button',{name:'+ Add Zombie',exact:true}).click();
await page.getByRole('button',{name:'+ Add Skeleton',exact:true}).click();
await page.getByRole('button',{name:'Battle',exact:true}).click();
await page.getByLabel('Zombie 1 initiative').fill('18'); await page.getByLabel('Skeleton 1 initiative').fill('10');
await page.getByRole('button',{name:'Start battle →'}).click();
await page.evaluate(()=>window.scrollTo(0,0));
await page.screenshot({path:`${dir}/battle-${width}.png`,fullPage:true});
results.geometry[width]=await page.evaluate(()=>({viewport:innerHeight,document:document.documentElement.scrollHeight,overflow:document.documentElement.scrollWidth>innerWidth,activeTop:document.querySelector('.actor.active').getBoundingClientRect().top,nextTop:[...document.querySelectorAll('button')].find(x=>x.textContent==='Next turn →')?.getBoundingClientRect().top}));
await page.locator('.actor').first().getByRole('button',{name:'Use / manage',exact:true}).click();
results.geometry[width].manageTop=await page.getByLabel('HP amount').evaluate(e=>e.getBoundingClientRect().top+scrollY);
await page.getByLabel('HP amount').fill('7'); await page.getByRole('button',{name:'Damage',exact:true}).click();
if(!await page.locator('.actor').first().locator('.vitals').innerText().then(t=>t.includes('15'))) throw Error('damage failed');
await page.getByRole('button',{name:'Heal',exact:true}).click();
await page.getByLabel('Toggle condition').selectOption('Prone');
await page.screenshot({path:`${dir}/manage-${width}.png`,fullPage:true});
await page.getByRole('button',{name:/↶ Undo/}).click();
if(await page.locator('.actor').first().locator('.tags').innerText()!=='')throw Error('undo condition failed');
await page.getByRole('button',{name:'Next turn →',exact:true}).click();
if(!await page.locator('.actor.active').innerText().then(t=>t.includes('Skeleton 1')))throw Error('next failed');
await page.getByRole('button',{name:'Next turn →',exact:true}).click();
await page.reload();
if(!await page.locator('.actor.active').innerText().then(t=>t.includes('Zombie 1')))throw Error('reload failed');
await page.locator('.actor').first().getByRole('button',{name:'Use / manage',exact:true}).click();
page.once('dialog',d=>d.accept()); await page.getByRole('button',{name:'Remove combatant',exact:true}).click();
if(await page.locator('.actor').count()!==1)throw Error('remove failed');
results.checks.push({width,result:'PASS',paths:['add Zombie + Skeleton','initiative totals','start','manual 7 damage → 15/22','heal → 22/22','Prone toggle','undo condition','next actor','round wrap','reload recovery','remove actor']});
await page.close();}
fs.writeFileSync(`${dir}/interaction-results.json`,JSON.stringify(results,null,2));
await browser.close();
